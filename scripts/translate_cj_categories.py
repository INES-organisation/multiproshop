def translate_categories():
    """Traduire toutes les catégories CJ en français via le champ name_fr"""
    with app.app_context():
        categories = Category.query.filter(
            Category.cj_category_id.isnot(None)
        ).all()

        print(f"\n{'='*80}")
        print(f"TRADUCTION DES CATÉGORIES CJ DROPSHIPPING")
        print(f"{'='*80}\n")

        translated = 0
        already_ok = 0
        not_found = []

        for cat in categories:
            name_en = cat.name

            # Si déjà traduit avec un nom FR différent du nom EN, on garde
            if cat.name_fr and cat.name_fr != cat.name:
                already_ok += 1
                continue

            if name_en in TRANSLATIONS:
                cat.name_fr = TRANSLATIONS[name_en]
                translated += 1
                print(f"  {name_en:55} -> {cat.name_fr}")
            else:
                not_found.append(name_en)

        db.session.commit()

        print(f"\n{'='*80}")
        print(f"  {translated} catégories traduites")
        print(f"  {already_ok} catégories déjà traduites")
        print(f"  {len(not_found)} catégories sans traduction")
        print(f"{'='*80}\n")

        if not_found:
            print("Catégories sans traduction :")
            for name in sorted(set(not_found)):
                print(f"  - '{name}'")
            print()


if __name__ == '__main__':
    translate_categories()
